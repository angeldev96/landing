// Slugs can carry accents (e.g. "Niña_tejida"), so paths are percent-encoded for sitemaps and schema.
export function absoluteUrl(path = "/") {
  if (path.startsWith("http")) {
    return path;
  }

  return `${SITE_URL}${encodeURI(path.startsWith("/") ? path : `/${path}`)}`;
}

// Collapses owner-written text into a single line that fits in a meta description.
export function toDescription(text: string | null | undefined, maxLength = 160) {
  const clean = (text ?? "").replace(/^#+\s*/gm, "").replace(/^\s*[-*]\s+/gm, "").replace(/\s+/g, " ").trim();

  if (clean.length <= maxLength) {
    return clean;
  }

  const cut = clean.slice(0, maxLength - 1);
  return `${cut.slice(0, cut.lastIndexOf(" ") > 0 ? cut.lastIndexOf(" ") : cut.length)}…`;
}

type PageMetadataInput = {
  title: string;
  description: string;
  path: string;
  images?: { url: string; alt?: string; width?: number; height?: number }[];
  type?: "website" | "article";
  publishedTime?: string | null;
  modifiedTime?: string | null;
  absoluteTitle?: boolean;
};

// Next merges openGraph shallowly, so every page sets the full object (including the default image).
export function pageMetadata({
  title,
  description,
  path,
  images,
  type = "website",
  publishedTime,
  modifiedTime,
  absoluteTitle = false,
}: PageMetadataInput): Metadata {
  const ogImages = images?.length ? images : [DEFAULT_OG_IMAGE];
  const fullTitle = absoluteTitle ? title : `${title} | ${SITE_NAME}`;

  return {
    title: absoluteTitle ? { absolute: title } : title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type,
      url: path,
      siteName: SITE_NAME,
      locale: SITE_LOCALE,
      title: fullTitle,
      description,
      images: ogImages,
      ...(type === "article"
        ? { publishedTime: publishedTime ?? undefined, modifiedTime: modifiedTime ?? undefined }
        : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: ogImages.map((image) => image.url),
    },
  };
}

