export function articleJsonLd({
  title,
  description,
  path,
  image,
  publishedAt,
  updatedAt,
  section,
  video,
}: {
  title: string;
  description: string;
  path: string;
  image: string | null;
  publishedAt: string | null;
  updatedAt: string | null;
  section: string;
  video: { embedUrl: string; contentUrl: string; thumbnailUrl: string } | null;
}): JsonLdNode {
  return {
    "@type": "Article",
    "@id": `${absoluteUrl(path)}#article`,
    headline: title,
    description,
    url: absoluteUrl(path),
    mainEntityOfPage: absoluteUrl(path),
    inLanguage: SITE_LANGUAGE,
    articleSection: section,
    image: image ? [image] : [absoluteUrl(DEFAULT_OG_IMAGE.url)],
    datePublished: publishedAt ?? undefined,
    dateModified: updatedAt ?? publishedAt ?? undefined,
    author: { "@id": ORGANIZATION_ID },
    publisher: { "@id": ORGANIZATION_ID },
    isPartOf: { "@id": WEBSITE_ID },
    ...(video
      ? {
          video: {
            "@type": "VideoObject",
            name: title,
            description,
            thumbnailUrl: video.thumbnailUrl,
            embedUrl: video.embedUrl,
            contentUrl: video.contentUrl,
            uploadDate: publishedAt ?? updatedAt ?? undefined,
          },
        }
      : {}),
  };
}

export function faqJsonLd(faqs: readonly { question: string; answer: string }[]): JsonLdNode {
  return {
    "@type": "FAQPage",
    "@id": `${SITE_URL}/#faq`,
    mainEntity: faqs.map((faq) => ({
      "@type": "Question",
      name: faq.question,
      acceptedAnswer: { "@type": "Answer", text: faq.answer },
    })),
  };
}
